Hyttiluokka = input("anna hyttiluokka (LUX,A,B,C:)")
if Hyttiluokka == "LUX":
    print("parvekeellinen hytti yläkannella")
elif Hyttiluokka =="A":
    print("Ikunnallinen hytti autokannen yläpuolella")
elif Hyttiluokka =="B":
    print("Ikkunaton hytti autokannen yläpuolella")
elif Hyttiluokka =="C":
    print("ikkunaton hytti autokannen alapuolella")
else:
    print("virheellinen hyttiluokka")