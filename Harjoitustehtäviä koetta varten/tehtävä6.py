hyttiluokka=input("anna hyttiluokka (LUX,A,B,C):")
if hyttiluokka=="LUX":
    print("LUX on parvekkellinen hytti yläkannella")
elif hyttiluokka=="A":
    print("A on ikkunallinen hytti atokannen yläpuolella")
elif hyttiluokka=="B":
    print("B on ikkunaton hytti autokanne yläpuolella")
elif hyttiluokka=="C":
    print("C on ikkunaton hytii autokanne alapuolella")
else: 
    print("virhellinen hytiiluokka!")